// Generates docs/reference/actions.md from the code: every skill exported from
// src/skills/index.ts, its actions, parameters (from the zod schemas) and flags, plus the
// behaviours brain's actions. Also fills the behaviour library table in
// docs/guide/behaviors.md (between the behaviors:start / behaviors:end markers).
//   node scripts/gen-docs.ts
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs'
import { z } from 'zod'
import * as skillExports from '../src/skills/index.ts'
import type { SkillDef, ActionDef } from '../src/core/index.ts'
import { behaviorActions, defaultBehaviorRegistry, LEVELS } from '../src/brains/behaviors/index.ts'

const OUT = 'docs/reference/actions.md'

function isSkill (v: unknown): v is SkillDef {
  return !!v && typeof v === 'object' && typeof (v as SkillDef).name === 'string' && Array.isArray((v as SkillDef).actions)
}

// Skill factories take no required arguments; helpers (fight, bestFood, ...) do.
const skills = new Map<string, SkillDef>()
for (const value of Object.values(skillExports)) {
  if (typeof value !== 'function' || value.length > 0 || value.constructor.name === 'AsyncFunction') continue
  let result: unknown
  try { result = (value as () => unknown)() } catch { continue }
  for (const s of Array.isArray(result) ? result : [result]) {
    if (isSkill(s) && !skills.has(s.name)) skills.set(s.name, s)
  }
}

interface JsonProp { type?: string | string[], description?: string, default?: unknown, minimum?: number, maximum?: number, enum?: unknown[] }

function paramRows (action: ActionDef): string[] {
  const schema = z.toJSONSchema(action.params, { io: 'input' }) as { properties?: Record<string, JsonProp>, required?: string[] }
  const props = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  return Object.entries(props).map(([name, p]) => {
    const type = p.enum ? p.enum.map(v => `\`${String(v)}\``).join(' \\| ') : (Array.isArray(p.type) ? p.type.join(' \\| ') : p.type ?? 'any')
    const range = p.minimum !== undefined || p.maximum !== undefined ? ` (${p.minimum ?? ''}..${p.maximum ?? ''})` : ''
    const def = p.default !== undefined ? `\`${JSON.stringify(p.default)}\`` : ''
    return `| \`${name}\` | ${type}${range} | ${required.has(name) && p.default === undefined ? 'yes' : ''} | ${def} | ${p.description ?? ''} |`
  })
}

function flags (a: ActionDef): string {
  const f: string[] = []
  if (a.exclusive === false) f.push('non-exclusive')
  if (a.longRunning) f.push('long-running')
  if (a.internal) f.push('internal')
  if (a.aliases?.length) f.push(`aliases: ${a.aliases.map(x => `\`${x}\``).join(', ')}`)
  return f.length ? `*${f.join(' · ')}*\n\n` : ''
}

const sorted = [...skills.values()].sort((a, b) => a.name.localeCompare(b.name))
const lines: string[] = [
  '---',
  'scope: mixed',
  'scopeNote: "Generated from the skills: most are Minecraft; the journal and config actions are game-agnostic."',
  '---',
  '',
  '# Action reference',
  '',
  '<!-- generated by scripts/gen-docs.ts, do not edit by hand (just docs-gen) -->',
  '',
  'Every action is a chat command (`!name args`), an LLM tool and a typed call (`agent.act(name, params)`).',
  'Positional chat arguments follow the parameter order below; `key=value` works too.',
  '',
  `${sorted.length} skills, ${sorted.reduce((n, s) => n + (s.actions?.length ?? 0), 0)} actions.`,
  ''
]
for (const s of sorted) {
  lines.push(`## ${s.name}`, '')
  if (s.description) lines.push(s.description, '')
  for (const a of s.actions ?? []) {
    lines.push(`### \`${a.name}\``, '', a.description, '')
    lines.push(flags(a).trimEnd())
    const rows = paramRows(a)
    if (rows.length) {
      lines.push('', '| param | type | required | default | description |', '|---|---|---|---|---|', ...rows)
    } else {
      lines.push('', 'No parameters.')
    }
    lines.push('')
  }
}
// The behaviours brain registers its actions itself (they exist on bots with behaviorsBrain()).
lines.push('## behaviors (brain)', '', 'Registered by `behaviorsBrain()`, see [Behaviours](../guide/behaviors.md).', '')
for (const a of behaviorActions) {
  lines.push(`### \`${a.name}\``, '', a.description, '', flags(a).trimEnd())
  const rows = paramRows(a)
  lines.push('', ...(rows.length ? ['| param | type | required | default | description |', '|---|---|---|---|---|', ...rows] : ['No parameters.']), '')
}
mkdirSync('docs/reference', { recursive: true })
writeFileSync(OUT, lines.join('\n').replace(/\n{3,}/g, '\n\n'))
console.log(`wrote ${OUT}: ${sorted.length} skills`)

// ------------------------------------------------------------------ behaviour library table
const GUIDE = 'docs/guide/behaviors.md'
if (existsSync(GUIDE)) {
  const reg = defaultBehaviorRegistry()
  const lib: string[] = ['<!-- generated by scripts/gen-docs.ts from the behaviour registry, do not edit by hand -->', '']
  for (const d of reg.list()) {
    const level = d.priority ?? 'npc'
    const needs = [...(d.requires ?? []).map(r => `\`${r}\``), d.needs?.dig ? 'digging' : '', d.needs?.place ? 'block placing' : ''].filter(Boolean)
    lib.push(`### \`${d.name}\``, '', `*${d.category} · priority ${level} (${LEVELS[level]})${needs.length ? ` · needs ${needs.join(', ')}` : ''}${d.uses?.length ? ` · uses ${d.uses.map(u => `\`${u}\``).join(', ')} when present` : ''}*`, '', d.description, '')
    const schema = z.toJSONSchema(reg.schema(d.name), { io: 'input' }) as { properties?: Record<string, JsonProp & { items?: { enum?: unknown[] } }> }
    const rows = Object.entries(schema.properties ?? {}).filter(([k]) => k !== 'priority').map(([k, p]) => {
      const type = p.enum ? p.enum.map(v => `\`${String(v)}\``).join(' \\| ') : p.type === 'array' ? `list${p.items?.enum ? ` of ${p.items.enum.join(', ')}` : ''}` : (Array.isArray(p.type) ? p.type.join(' \\| ') : p.type ?? 'any')
      const range = p.minimum !== undefined || p.maximum !== undefined ? ` (${p.minimum ?? ''}..${p.maximum ?? ''})` : ''
      const def = p.default !== undefined ? `\`${JSON.stringify(p.default)}\`` : ''
      return `| \`${k}\` | ${type}${range} | ${def} | ${p.description ?? ''} |`
    })
    lib.push(...(rows.length ? ['| option | type | default | description |', '|---|---|---|---|', ...rows] : ['No options.']), '')
  }
  const text = readFileSync(GUIDE, 'utf8')
  const start = '<!-- behaviors:start -->'
  const end = '<!-- behaviors:end -->'
  const a = text.indexOf(start)
  const b = text.indexOf(end)
  if (a >= 0 && b > a) {
    writeFileSync(GUIDE, text.slice(0, a + start.length) + '\n' + lib.join('\n').replace(/\n{3,}/g, '\n\n') + '\n' + text.slice(b))
    console.log(`wrote ${GUIDE}: ${reg.list().length} behaviours`)
  }
}
